/**
 * KI-Interpretation eines Diagramms (Leseanleitung + Benchmark für die Hochschulleitung).
 *
 * Deutlich als KI-generiert gekennzeichnet: violettes "AI-GENERATED"-Tag, Modell und
 * Datum im Fuss, Hinweis, dass Fehler möglich sind. Text ist Englisch.
 * Prototyp: Texte mit Claude aus synthetischen Daten; später Gemini im Backend.
 */
import type { ChartInsight } from '../../domain/insights';
import './AiInsightCard.css';

/**
 * Geschützte Leerzeichen: kein Zeilenumbruch zwischen Zahl und Einheit ("92.6 %",
 * "1.9 pp") bzw. in "n = 29". Ändert nur die Anzeige, nicht den gespeicherten Text.
 */
export function keepTogether(text: string): string {
  return text
    .replace(/(\d) (%|pp\b)/g, '$1\u00A0$2')
    .replace(/\bn = (\d)/g, 'n\u00A0=\u00A0$1');
}

/** Datum "15 Oct 2026" (en-GB). */
function fmtDate(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : new Intl.DateTimeFormat('en-GB', { dateStyle: 'medium' }).format(d);
}

/** Karte mit Überschrift, Befunden, Benchmark, Leseanleitung und KI-Hinweis. */
export function AiInsightCard({ insight }: { insight: ChartInsight }) {
  const date = fmtDate(insight.generatedAt);
  return (
    <section className="ai-card" aria-label="AI-generated interpretation">
      <div className="ai-card__tag">
        <span aria-hidden="true">✦</span> AI-generated interpretation
      </div>
      <p className="ai-card__headline">{keepTogether(insight.headline)}</p>

      {insight.keyFindings.length > 0 && (
        <ul className="ai-card__findings">
          {insight.keyFindings.map((f) => (
            <li key={f}>{keepTogether(f)}</li>
          ))}
        </ul>
      )}

      {insight.benchmark && (
        <div className="ai-card__block">
          <div className="ai-card__label">Benchmark</div>
          <p>{keepTogether(insight.benchmark)}</p>
        </div>
      )}

      <div className="ai-card__block">
        <div className="ai-card__label">How to read the chart</div>
        <p>{keepTogether(insight.howToRead)}</p>
      </div>

      {insight.caveats && <p className="ai-card__caveat">{keepTogether(insight.caveats)}</p>}

      <p className="ai-card__foot">
        Generated by AI ({insight.generatedBy.model}{date ? `, ${date}` : ''}) from aggregated survey data
        – prototype based on synthetic data. AI can make mistakes; please check against the chart.
      </p>
    </section>
  );
}
